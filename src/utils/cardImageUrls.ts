export const THOTH_CARD_BACK_IMAGE = '/images/thoth/card-back.webp';

export const CARD_IMAGE_MAP: Record<string, string> = {
  ...CLASSIC_RENAISSANCE_IMAGE_MAP,
  ...BOOK_OF_THOTH_IMAGE_MAP,
};

export function getThothCardImageUrl(cardOrId: any): string {
  if (!cardOrId) return THOTH_CARD_BACK_IMAGE;
  if (typeof cardOrId === 'string') {
    return BOOK_OF_THOTH_IMAGE_MAP[cardOrId] || CLASSIC_RENAISSANCE_IMAGE_MAP[cardOrId] || THOTH_CARD_BACK_IMAGE;
  }
  return (
    cardOrId.bookOfThothImageUrl ||
    cardOrId.imageUrl ||
    (cardOrId.id ? BOOK_OF_THOTH_IMAGE_MAP[cardOrId.id] : undefined) ||
    (cardOrId.id ? CLASSIC_RENAISSANCE_IMAGE_MAP[cardOrId.id] : undefined) ||
    THOTH_CARD_BACK_IMAGE
  );
}

export function getClassicCardImageUrl(cardOrId: any): string {
  if (!cardOrId) return THOTH_CARD_BACK_IMAGE;
  if (typeof cardOrId === 'string') {
    return CLASSIC_RENAISSANCE_IMAGE_MAP[cardOrId] || BOOK_OF_THOTH_IMAGE_MAP[cardOrId] || THOTH_CARD_BACK_IMAGE;
  }
  return (
    cardOrId.classicImageUrl ||
    (cardOrId.id ? CLASSIC_RENAISSANCE_IMAGE_MAP[cardOrId.id] : undefined) ||
    cardOrId.bookOfThothImageUrl ||
    cardOrId.imageUrl ||
    (cardOrId.id ? BOOK_OF_THOTH_IMAGE_MAP[cardOrId.id] : undefined) ||
    THOTH_CARD_BACK_IMAGE
  );
}

